function withCoreWorkflows(list: Product[]): Product[] {
  return list.map((product) => {
    const extras = extraWorkflows[product.slug] ?? [];
    if (extras.length === 0) return product;
    const seen = new Set(product.workflows.map((w) => w.name.toLowerCase()));
    const merged = [...product.workflows];
    for (const workflow of extras) {
      if (seen.has(workflow.name.toLowerCase())) continue;
      seen.add(workflow.name.toLowerCase());
      merged.push(workflow);
    }
    return { ...product, workflows: merged };
  });
}

